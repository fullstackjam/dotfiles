#!/usr/bin/env python3
"""Deploy personal configuration with an optional local extension."""
from __future__ import annotations

import argparse
import ast
import json
import os
from pathlib import Path
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ["git", "ssh", "zsh", "ghostty", "zed"]


def run(*args):
    subprocess.run(args, cwd=ROOT, check=True)


def linked_to(path, source):
    return path.is_symlink() and Path(os.path.abspath(path.parent / os.readlink(path))) == source


def atomic_write(path, text):
    if path.exists() and not path.is_symlink() and path.read_text() == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(dir=path.parent, prefix=".dotfiles-")
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(text)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


class Deployment:
    def __init__(self, target, extra_source=None, without_extra=False):
        self.target = target.resolve()
        self.runtime = self.target / ".local/share/dotfiles"
        self.manifest = self.runtime / "links.json"
        for path in [self.runtime, *self.runtime.parents]:
            if path == self.target:
                break
            if path.is_symlink() or (path.exists() and not path.is_dir()):
                raise ValueError(f"Expected a real runtime directory: {path}")
        if self.manifest.is_symlink():
            raise ValueError(f"Manifest must not be a symlink: {self.manifest}")
        self.sources_file = self.runtime / "sources.json"
        if self.sources_file.is_symlink():
            raise ValueError(f"Sources file must not be a symlink: {self.sources_file}")
        saved = json.loads(self.sources_file.read_text()) if self.sources_file.exists() else {}
        selected = None if without_extra else (extra_source or saved.get("extra_source"))
        self.extra = Path(selected).expanduser().resolve() if selected else None
        self.old = json.loads(self.manifest.read_text()) if self.manifest.exists() else {}
        self.links = {}
        self.legacy = {
            ".codex/AGENTS.md": ROOT / "codex/.codex/AGENTS.md",
            ".config/git/identity.conf": ROOT / "git/.config/git/identity.conf",
        }
        self.agent_root = self.target / ".agents"
        self.migrate = linked_to(self.agent_root, ROOT / "agents/.agents")

    def prepare(self):
        if self.target.is_relative_to(ROOT):
            raise ValueError("Deployment target must be outside the source repository")
        instructions = ROOT / "codex/.codex/AGENTS.md"
        if not instructions.is_file():
            raise ValueError(f"Missing instructions: {instructions}")
        self.links[".codex/AGENTS.md"] = instructions
        skills = [skill for skill in sorted((ROOT / "agents/.agents/skills").iterdir())
                  if (skill / "SKILL.md").is_file()]
        for skill in skills:
            self.links[f".agents/skills/{skill.name}"] = skill
        self.skill_count = len(skills)
        self.generated_instructions = None
        self.extra_files = []
        if self.extra:
            if self.extra == ROOT:
                raise ValueError("Local extension must be separate from the personal repository")
            config = json.loads((self.extra / "deployment.json").read_text())
            for relative, source in config.get("files", {}).items():
                self.add_extra_link(relative, self.extra_path(source))
                self.extra_files.append(self.links[relative])
            if config.get("skills"):
                for skill in sorted(self.extra_path(config["skills"], directory=True).iterdir()):
                    if (skill / "SKILL.md").is_file():
                        self.add_extra_link(f".agents/skills/{skill.name}", self.extra_path(str(skill.relative_to(self.extra)), directory=True))
                        self.skill_count += 1
            if config.get("instructions"):
                extra_instructions = self.extra_path(config["instructions"])
                self.generated_instructions = (
                    "<!-- Generated by make install; edit source repositories. -->\n\n"
                    + instructions.read_text().rstrip() + "\n\n" + extra_instructions.read_text().rstrip() + "\n"
                )
                self.links[".codex/AGENTS.md"] = self.runtime / "AGENTS.md"
        self.preflight()

    def extra_path(self, relative, directory=False):
        rel = Path(relative)
        source = (self.extra / rel).resolve()
        if rel.is_absolute() or ".." in rel.parts or not source.is_relative_to(self.extra):
            raise ValueError(f"Invalid extension source: {relative}")
        if not (source.is_dir() if directory else source.is_file()):
            raise ValueError(f"Missing extension source: {source}")
        return source

    def add_extra_link(self, relative, source):
        if relative in self.links:
            raise ValueError(f"Duplicate managed path: {relative}")
        # Local extensions may not replace files managed by Stow packages.
        if any((ROOT / package / relative).is_file() for package in PACKAGES):
            raise ValueError(f"Extension conflicts with a personal package: {relative}")
        if relative.startswith(".local/bin/") and not os.access(source, os.X_OK):
            raise ValueError(f"Command must be executable: {source}")
        self.links[relative] = source

    def preflight(self):
        if self.migrate:
            extra = {p.name for p in self.agent_root.iterdir()} - {"skills", ".skill-lock.json", "AGENTS.md"}
            if extra:
                raise ValueError(f"Move existing agent runtime data out of the source first: {sorted(extra)}")
        # Refuse redirected runtime directories before reading/writing generated files.
        paths = list(self.links) + list(self.old) + [".local/share/dotfiles/AGENTS.md", ".local/share/dotfiles/links.json", ".local/share/dotfiles/sources.json"]
        for relative in paths:
            rel = Path(relative)
            if rel.is_absolute() or ".." in rel.parts or not rel.parts or relative == ".":
                raise ValueError(f"Invalid managed path: {relative}")
            if relative.startswith(".local/share/dotfiles/") and relative in self.links:
                raise ValueError(f"Extension cannot manage installer state: {relative}")
            dest = self.target / relative
            for parent in dest.parents:
                if parent == self.target:
                    break
                if self.migrate and (parent == self.agent_root or parent.is_relative_to(self.agent_root)):
                    continue
                if parent.is_symlink() or (parent.exists() and not parent.is_dir()):
                    raise ValueError(f"Expected a real directory: {parent}")
            if relative.startswith(".local/share/dotfiles/"):
                if dest.is_symlink():
                    raise ValueError(f"Generated file must not be a symlink: {dest}")
                continue
            if not dest.exists() and not dest.is_symlink():
                continue
            if self.migrate and relative.startswith(".agents/skills/"):
                if dest.resolve() == self.links.get(relative):
                    continue
            owners = [self.links.get(relative), self.legacy.get(relative)]
            if relative in self.old:
                owners.append(Path(self.old[relative]))
            if not any(owner and linked_to(dest, owner) for owner in owners):
                raise ValueError(f"Refusing to replace an unmanaged path: {dest}")

    def stow(self, mode):
        run("stow", mode, "-v", "--no-folding",
            "--target=" + str(self.target), *PACKAGES)

    def check(self):
        self.prepare()
        for filename in [".zshenv", ".zprofile", ".zshrc"]:
            run("zsh", "-n", str(ROOT / "zsh" / filename))
        ast.parse(Path(__file__).read_text())
        for source in self.extra_files:
            if source.suffix == ".zsh":
                run("zsh", "-n", str(source))
            elif source.suffix == ".py" or source.read_bytes().startswith((b"#!/usr/bin/python", b"#!/usr/bin/env python")):
                ast.parse(source.read_text())
        subprocess.run(["git", "config", "--file", str(ROOT / "git/.gitconfig"), "--list"],
                       check=True, stdout=subprocess.DEVNULL)
        run("git", "diff", "--check")
        run("git", "diff", "--cached", "--check")
        if self.extra:
            for args in [("diff", "--check"), ("diff", "--cached", "--check")]:
                run("git", "-C", str(self.extra), *args)
            for source in self.extra_files:
                if source.parent.name == "git":
                    subprocess.run(["git", "config", "--file", str(source), "--list"],
                                   check=True, stdout=subprocess.DEVNULL)
        self.stow("-n")
        print(f"CHECK PASS: {self.skill_count} skills; extension={'enabled' if self.extra else 'disabled'}; no files written")

    def install(self):
        self.check()
        if self.migrate:
            lock = self.agent_root / ".skill-lock.json"
            lock_text = lock.read_text() if lock.exists() else None
            self.agent_root.unlink()
            self.agent_root.mkdir()
            if lock_text is not None:
                atomic_write(self.agent_root / ".skill-lock.json", lock_text)
        self.runtime.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.chmod(self.runtime, 0o700)
        if self.generated_instructions is not None:
            atomic_write(self.runtime / "AGENTS.md", self.generated_instructions)
        # Complete desired links before removing obsolete ones; never delete source files.
        for relative, source in self.links.items():
            dest = self.target / relative
            if linked_to(dest, source):
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            if dest.is_symlink():
                dest.unlink()
            dest.symlink_to(source)
        for relative, source in self.old.items():
            if relative not in self.links:
                dest = self.target / relative
                if linked_to(dest, Path(source)):
                    dest.unlink()
        retired_instructions = self.runtime / "AGENTS.md"
        if (self.generated_instructions is None
                and self.old.get(".codex/AGENTS.md") == str(retired_instructions)
                and retired_instructions.is_file()
                and retired_instructions.read_text().startswith("<!-- Generated by make install;")):
            retired_instructions.unlink()
        for relative in [".config/dotfiles/work", ".config/dotfiles"]:
            directory = self.target / relative
            if directory.is_dir() and not directory.is_symlink() and not any(directory.iterdir()):
                directory.rmdir()
        atomic_write(self.manifest, json.dumps({k: str(v) for k, v in self.links.items()}, indent=2) + "\n")
        atomic_write(self.sources_file, json.dumps({"extra_source": str(self.extra)} if self.extra else {}, indent=2) + "\n")
        self.stow("-S")
        for relative in self.links:
            if not (self.target / relative).exists():
                raise ValueError(f"Broken deployed link: {relative}")
        print(f"INSTALL PASS: {self.skill_count} skills; sources unchanged; runtime={self.runtime}")

    def uninstall(self):
        # Only unlink paths still owned by the saved manifest. Keep user additions and state.
        for relative, source in self.old.items():
            rel = Path(relative)
            if rel.is_absolute() or ".." in rel.parts:
                raise ValueError(f"Invalid managed path: {relative}")
            dest = self.target / rel
            if any(p.is_symlink() for p in dest.parents if p != self.target and p.is_relative_to(self.target)):
                raise ValueError(f"Refusing to unlink through a redirected directory: {dest}")
            if linked_to(dest, Path(source)):
                dest.unlink()
        self.stow("-D")
        if self.manifest.exists():
            self.manifest.unlink()
        if self.sources_file.exists():
            self.sources_file.unlink()
        generated = self.runtime / "AGENTS.md"
        if generated.is_file() and not generated.is_symlink() and generated.read_text().startswith("<!-- Generated by make install;"):
            generated.unlink()
        print("UNINSTALL PASS: managed links removed; source files and runtime data retained")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["check", "install", "uninstall"])
    parser.add_argument("--target", type=Path, default=Path.home())
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--extra-source", type=Path, help="Register a local extension (remembered after install)")
    group.add_argument("--without-extra", action="store_true", help="Detach the local extension while retaining personal configuration")
    args = parser.parse_args()
    try:
        deployment = Deployment(args.target, args.extra_source, args.without_extra)
        getattr(deployment, args.action)()
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f"Deployment failed: {exc}\n")


if __name__ == "__main__":
    main()
